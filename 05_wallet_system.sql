-- FASE 1: ARSITEKTUR DATABASE DOMPET & PENARIKAN (WALLET SYSTEM)

-- 1. Modifikasi tabel organizer_profile untuk menampung data rekening bank
ALTER TABLE organizer_profile 
ADD COLUMN IF NOT EXISTS bank_nama VARCHAR(50),
ADD COLUMN IF NOT EXISTS bank_rekening VARCHAR(50),
ADD COLUMN IF NOT EXISTS bank_atas_nama VARCHAR(100);

-- 2. Modifikasi tabel peserta untuk menampung status dana (Dompet)
-- status_dana: 'PENDING' (menunggu cair dari QRIS/Bank), 'CAIR' (uang sudah bisa ditarik EO)
ALTER TABLE peserta 
ADD COLUMN IF NOT EXISTS status_dana VARCHAR(20) DEFAULT 'PENDING';

-- [Trik Bypass Sementara]: Otomatis ubah data lama yang sudah 'paid' menjadi 'CAIR' 
UPDATE peserta SET status_dana = 'CAIR' WHERE status_bayar = 'paid';

-- 3. Buat tabel penarikan_dana untuk mencatat mutasi & antrean request
CREATE TABLE IF NOT EXISTS penarikan_dana (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizer_id UUID REFERENCES organizer_profile(id) ON DELETE CASCADE,
    nominal BIGINT NOT NULL,
    bank_tujuan VARCHAR(50) NOT NULL,
    rekening_tujuan VARCHAR(50) NOT NULL,
    atas_nama VARCHAR(100) NOT NULL,
    status VARCHAR(20) DEFAULT 'REQUEST', -- Bisa berisi: REQUEST, PROSES, SELESAI, DITOLAK
    keterangan TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Pengamanan RLS (Row Level Security) agar EO lain tidak bisa ngintip dompet saingannya
ALTER TABLE penarikan_dana ENABLE ROW LEVEL SECURITY;

CREATE POLICY "EO bisa melihat riwayat penarikannya sendiri" 
ON penarikan_dana FOR SELECT 
USING (auth.uid() = organizer_id);

CREATE POLICY "EO bisa membuat request penarikan" 
ON penarikan_dana FOR INSERT 
WITH CHECK (auth.uid() = organizer_id);

